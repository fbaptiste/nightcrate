def label_sort_expression(column: str, labels: dict[str, str]) -> tuple[str, list[str]]:
    """Build a bound CASE expression with the frontend's unknown-code fallback."""
    whens = " ".join("WHEN ? THEN ?" for _ in labels)
    params = [value for item in labels.items() for value in item]
    expression = (
        f"CASE WHEN NULLIF(TRIM({column}), '') IS NULL THEN NULL "
        f"ELSE CASE {column} {whens} ELSE {column} END END COLLATE NOCASE"
    )
    return expression, params
